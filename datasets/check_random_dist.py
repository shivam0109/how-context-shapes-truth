"""
This script checks the distribution of the random data generated by the generate_random_data.py script.
Compares word count distributions of random_char, random_word, random_salad, and random_wiki 
against the context_col from an original dataset.

"""

import pandas as pd
import matplotlib.pyplot as plt
import argparse
import os

def check_random_dist(original_df_path, random_df_path, context_col, output_path):
    """
    Compare word count distributions of random data against original context column.
    
    Args:
        original_df_path: Path to the original dataset CSV
        random_df_path: Path to the random data CSV
        context_col: Name of the context column in the original dataset
        output_path: Path to save the comparison plot
    """
    # Load datasets
    print("Loading datasets...")
    original_df = pd.read_csv(original_df_path)
    random_df = pd.read_csv(random_df_path)
    
    print(f"Original dataset shape: {original_df.shape}")
    print(f"Random dataset shape: {random_df.shape}")
    
    # Check if context_col exists in original dataset
    if context_col not in original_df.columns:
        raise ValueError(f"Column '{context_col}' not found in original dataset. Available columns: {list(original_df.columns)}")
    
    # Check if random columns exist - dynamically detect all random_* columns
    random_cols = [col for col in random_df.columns if col.startswith('random_')]
    if not random_cols:
        raise ValueError(f"No random columns found in random dataset. Available columns: {list(random_df.columns)}")
    print(f"Found {len(random_cols)} random columns: {random_cols}")
    
    # Calculate word counts
    print("Calculating word counts...")
    original_lengths = original_df[context_col].astype(str).str.split().str.len()
    random_lengths = {}
    
    for col in random_cols:
        random_lengths[col] = random_df[col].astype(str).str.split().str.len()
    
    # Create subplots
    fig, axes = plt.subplots(2, 2, figsize=(15, 12))
    fig.suptitle('Distribution Comparison - Relevant vs Non-Relevant Context', fontsize=16)
    
    # Plot each random column
    for i, col in enumerate(random_cols):
        row = i // 2
        col_idx = i % 2
        ax = axes[row, col_idx]
        
        # Create histograms
        ax.hist(original_lengths, bins=50, alpha=0.7, label='context (relevant)', 
                color='blue', density=True)
        ax.hist(random_lengths[col], bins=50, alpha=0.7, label=f'{col} (non-relevant)', 
                color='red', density=True)
        
        # Customize subplot
        ax.set_title(f'{col} vs context')
        ax.set_xlabel('Word Count')
        ax.set_ylabel('Density')
        ax.legend()
        ax.grid(True, alpha=0.3)
        
        # Add statistics
        orig_mean = original_lengths.mean()
        random_mean = random_lengths[col].mean()
        orig_std = original_lengths.std()
        random_std = random_lengths[col].std()
        
        stats_text = f'Relevant: mu={orig_mean:.1f}, std={orig_std:.1f}\nNon-relevant: mu={random_mean:.1f}, std={random_std:.1f}'
        ax.text(0.02, 0.98, stats_text, transform=ax.transAxes, 
                verticalalignment='top', bbox=dict(boxstyle='round', facecolor='wheat', alpha=0.8))
    
    plt.tight_layout()
    
    # Save plot
    os.makedirs(os.path.dirname(output_path), exist_ok=True)
    plt.savefig(output_path, dpi=300, bbox_inches='tight')
    print(f"Plot saved to: {output_path}")
    
    # Print summary statistics
    print("\nSummary Statistics (Word Counts):")
    print(f"{'Column':<15} {'Mean':<10} {'Std':<10} {'Min':<10} {'Max':<10}")
    print("-" * 60)
    print(f"{context_col:<15} {original_lengths.mean():<10.1f} {original_lengths.std():<10.1f} {original_lengths.min():<10} {original_lengths.max():<10}")
    
    for col in random_cols:
        lengths = random_lengths[col]
        print(f"{col:<15} {lengths.mean():<10.1f} {lengths.std():<10.1f} {lengths.min():<10} {lengths.max():<10}")

def get_context_column(dataset_key):
    context_map = {
        'druid': 'evidence',
        'mf2': 'synopsis',
        'cl_bill': 'bill_summary',
        'cl_company': 'company_description',
        'conflictqa': 'evidence'
    }
    return context_map.get(dataset_key)


def plot_all_datasets_implicit(base_dir, output_path):
    dataset_configs = [
        ('druid/borderlines', 'druid', 'druid/df_borderlines_implicit_random_data.csv'),
        ('druid/politifact', 'druid', 'druid/df_politifact_implicit_random_data.csv'),
        ('druid/sciencefeedback_cluster1', 'druid', 'druid/df_sciencefeedback_cluster1_implicit_random_data.csv'),
        ('mf2', 'mf2', 'mf2/df_mf2_implicit_random_data.csv'),
        ('corporate_lobbying/bill', 'cl_bill', 'legalbench/corporate_lobbying/df_corporate_lobbying_bill_random_data_v2.csv'),
        ('corporate_lobbying/company', 'cl_company', 'legalbench/corporate_lobbying/df_corporate_lobbying_company_random_data_v2.csv'),
        ('conflictqa/counter', 'conflictqa', 'conflictqa/df_conflictqa_counter_random_data.csv'),
        ('conflictqa/parametric', 'conflictqa', 'conflictqa/df_conflictqa_parametric_random_data.csv'),
    ]
    
    random_types = ['random_char', 'random_word', 'random_salad', 'random_wiki']
    
    fig, axes = plt.subplots(8, 4, figsize=(20, 32))
    fig.suptitle('Distribution Comparison - Relevant vs Non-Relevant Context', fontsize=16, y=0.995)
    
    handles = None
    labels = None
    
    for dataset_idx, (dataset_path, dataset_key, random_file) in enumerate(dataset_configs):
        context_col = get_context_column(dataset_key)
        
        random_df_path = os.path.join(base_dir, random_file)
        random_df = pd.read_csv(random_df_path)
        
        original_lengths = random_df[context_col].astype(str).str.split().str.len()
        
        for random_idx, random_type in enumerate(random_types):
            ax = axes[dataset_idx, random_idx]
            
            random_lengths = random_df[random_type].astype(str).str.split().str.len()
            
            hist1 = ax.hist(original_lengths, bins=50, alpha=0.7, label='relevant context', 
                    color='#0066CC', density=True, edgecolor='#003d7a', linewidth=0.5)
            hist2 = ax.hist(random_lengths, bins=50, alpha=0.5, label='non-relevant context', 
                    color='#FF6B35', density=True, edgecolor='#cc5500', linewidth=0.5)
            
            if dataset_idx == 0 and random_idx == 0:
                handles, labels = ax.get_legend_handles_labels()
            
            if dataset_idx == 0:
                ax.set_title(random_type)
            if random_idx == 0:
                dataset_label = dataset_path.replace('/', '-').replace('sciencefeedback_cluster1', 'sciencefeedback')
                ax.set_ylabel(f'{dataset_label}\nDensity', rotation=90, labelpad=20)
            
            ax.set_xlabel('Word Count')
            ax.grid(True, alpha=0.3)
            
            orig_mean = original_lengths.mean()
            random_mean = random_lengths.mean()
            orig_std = original_lengths.std()
            random_std = random_lengths.std()
            
            stats_text = f'Relevant: mu={orig_mean:.1f}, std={orig_std:.1f}\nNon-relevant: mu={random_mean:.1f}, std={random_std:.1f}'
            ax.text(0.02, 0.98, stats_text, transform=ax.transAxes, 
                    verticalalignment='top', bbox=dict(boxstyle='round', facecolor='wheat', alpha=0.8))
    
    fig.legend(handles, labels, loc='upper center', bbox_to_anchor=(0.5, 0.99), ncol=2, fontsize=12)
    plt.tight_layout(rect=[0, 0, 1, 0.97])
    os.makedirs(os.path.dirname(output_path), exist_ok=True)
    plt.savefig(output_path, dpi=300, bbox_inches='tight')
    print(f"Plot saved to: {output_path}")
    plt.close()


def main():
    parser = argparse.ArgumentParser(description='Compare word count distributions of random data against original context')
    parser.add_argument('--original_df_path', type=str, required=False, 
                       help='Path to the original dataset CSV')
    parser.add_argument('--random_df_path', type=str, required=False,
                       help='Path to the random data CSV')
    parser.add_argument('--context_col', type=str, required=False,
                       help='Name of the context column in the original dataset')
    parser.add_argument('--output_path', type=str, required=False,
                       help='Path to save the comparison plot')
    parser.add_argument('--base_dir', type=str, required=False,
                       help='Base directory for plotting all datasets')
    parser.add_argument('--all_datasets_output', type=str, required=False,
                       help='Output path for all datasets plot')
    
    args = parser.parse_args()
    
    if args.base_dir and args.all_datasets_output:
        plot_all_datasets_implicit(args.base_dir, args.all_datasets_output)
    elif args.original_df_path and args.random_df_path and args.context_col and args.output_path:
        check_random_dist(args.original_df_path, args.random_df_path, 
                         args.context_col, args.output_path)
    else:
        parser.error("Either provide (base_dir, all_datasets_output) or (original_df_path, random_df_path, context_col, output_path)")

if __name__ == "__main__":
    main()